"""Actual 27B FFN geometry with the retained independent four-value oracle.

Regenerate the two adjacent Loom fixtures. The shared helpers encode explicit
Q4_K blocks; expected arithmetic never decodes or reads the encoded buffers.
Only outer parameter-bank guards are checked, not unused internal padding.
"""
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).parent
COMMON = ROOT.parents[2] / 'kernels/qwen/testing/common'
spec = importlib.util.spec_from_file_location('fixture_helpers', COMMON/'fixture_helpers.py')
h = importlib.util.module_from_spec(spec)
spec.loader.exec_module(h)
h.out.clear()
E, F, W, BANK = 5120, 17408, 50135040, 160000000
assert E*F//256*144 == W
header = '// Copyright 2026 AMD ROCm Software\n// SPDX-License-Identifier: MIT\n// Generated by ffn27_fixtures.py; real geometry, independent deterministic anchors.\n'
# Reuse maintained test configuration/declarations, with actual 27B dimensions.
base = (COMMON/'common_programs.loom').read_text()
config = base[base.index('config.def'):base.index('kernel.decl')]
values = {1024:E,3584:F,4096:E*4,14336:F*4,4608:E//128*144*4,
          2064384:W,2523136:W,3010560:W,2097152:512*E*4,
          7340032:512*F*4,589824:128*E//128*144,6144:F,32768:512*F//128}
config = re.sub(r'\b\d+\b', lambda m: str(values.get(int(m[0]),int(m[0]))), config)
h.emit(header+config)
h.emit(f'''func.def public pure inline @loomify.config.layer_ffn(%layer:index) -> (index,index,index,index,index,index,index) where [range(%layer,0,63)] {{
  %f = index.constant {F} : index
  %q4 = index.constant 12 : index
  %bytes = index.constant {W} : index
  func.return %f,%q4,%q4,%q4,%bytes,%bytes,%bytes : index,index,index,index,index,index,index
}}
''')
# Public numerical ABI declarations stay identical to the existing tests.
h.emit(base[base.index('command.program.decl @qwen38_ffn_down_decode'):base.index('command.program.def public retain')])
h.emit('kernel.decl @ggml_quantize_q8_1_x4_f32(%rows:index,%width:index) launch(%rows:index,%width:index,%input:buffer,%output:buffer)\n')
checks=[header]
for rows in (1,3):
    name=f'ffn27_{rows}'
    initial, activation, result = h.ffn_anchors(rows,E,F)
    body=h.prefix()+h.input_body(rows,E,True)+'\n'
    body+=h.weight_body(12,E,'gate','gate','g')+h.weight_body(12,E,'up','up','u')
    body+=f'  %hidden = index.constant {E} : index\n  %small = index.cmp ult, %channel, %hidden : index\n  scf.if %small {{\n'
    body+=h.weight_body(12,F,'down','down','d')+h.store_pattern(rows,E,'residual',initial,'res')+'  }\n'
    h.kernel('test.init.'+name,F,'%input: buffer, %gate: buffer, %up: buffer, %down: buffer, %residual: buffer',body)
    h.kernel('test.expected.'+name,F,'%input: buffer, %activation: buffer, %residual: buffer',h.prefix()+h.input_body(rows,E,True)+'\n'+h.store_pattern(rows,F,'activation',activation,'act')+h.store_pattern(rows,E,'residual',result,'final'))
    h.reference(name,F,'%root: buffer, %input: buffer, %residual: buffer, %activation: buffer, %control: buffer',f'    func.call @test.expected.{name}.body(%channel, %input, %activation, %residual) : (index, buffer, buffer, buffer) -> ()')
    # Existing decode quantizer + maintained gate/up and down programs.
    h.emit(f'''command.program.def public retain @actual.{name}() launch(%root:buffer,%input:buffer,%residual:buffer,%activation:buffer,%control:buffer) {{
  command.serial {{
    %layer = index.constant 0 : index
    %rows = index.constant {rows} : index
    %hidden = index.constant {E} : index
    %zero = index.constant 0 : index
    %one = index.constant 1 : index
    %bytes = index.constant {W} : index
    %gate = command.parameter %root,"blk.{{}}.ffn_gate.weight"[%layer] : view<[%bytes]xi8>
    %up = command.parameter %root,"blk.{{}}.ffn_up.weight"[%layer] : view<[%bytes]xi8>
    %down = command.parameter %root,"blk.{{}}.ffn_down.weight"[%layer] : view<[%bytes]xi8>
    kernel.launch @test.init.{name}(%input,%gate,%up,%down,%residual) : (buffer,view<[%bytes]xi8>,view<[%bytes]xi8>,view<[%bytes]xi8>,buffer)
''')
    if rows==1:
        h.emit(f'''    %packed_bytes = index.constant {E//128*144} : offset
    %packed = buffer.alloca<global> align(256) %packed_bytes : buffer
    kernel.launch @ggml_quantize_q8_1_x4_f32[%rows,%hidden](%rows,%hidden,%input,%packed) : [index,index](index,index,buffer,buffer)
    command.program.launch @qwen38_ffn_gate_up_decode[%layer](%root,%packed,%activation) : [index](buffer,buffer,buffer)
    command.program.launch @qwen38_ffn_down_decode[%layer](%root,%activation,%residual) : [index](buffer,buffer,buffer)
''')
    else:
        h.emit('''    command.program.launch @qwen38_ffn_gate_up_prefill[%rows,%rows,%layer,%zero,%one](%root,%input,%control,%activation) : [index,index,index,index,index](buffer,buffer,buffer,buffer)
    command.program.launch @qwen38_ffn_down_prefill[%rows,%rows,%layer,%zero,%one](%root,%control,%activation,%residual) : [index,index,index,index,index](buffer,buffer,buffer,buffer)
''')
    h.emit('  }\n  command.return\n}\n')
    R,A=rows*E,rows*F
    checks.append(f'''command.program.decl @actual.{name}() launch(%root:buffer,%input:buffer,%residual:buffer,%activation:buffer,%control:buffer)
func.decl @reference.{name}(%root:buffer,%input:buffer,%residual:buffer,%activation:buffer,%control:buffer)
check.scenario @{name} {{
  check.trial[1](%trial:index,%entropy:check.entropy) {{
    %root_storage = check.generate.fill value(77) : tensor<{BANK+512}xi8>
    %root = check.tensor.view %root_storage offset(256) : tensor<{BANK+512}xi8> -> tensor<{BANK}xi8>
    %root_before = check.tensor.view %root_storage offset(0) : tensor<{BANK+512}xi8> -> tensor<256xi8>
    %root_after = check.tensor.view %root_storage offset({BANK+256}) : tensor<{BANK+512}xi8> -> tensor<256xi8>
    %input = check.generate.fill value(-7.0) : tensor<{R}xf32>
    %residual_storage = check.generate.fill value(-99.0) : tensor<{R+4}xf32>
    %residual = check.tensor.view %residual_storage offset(8) : tensor<{R+4}xf32> -> tensor<{R}xf32>
    %residual_before = check.tensor.view %residual_storage offset(0) : tensor<{R+4}xf32> -> tensor<2xf32>
    %residual_after = check.tensor.view %residual_storage offset({(R+2)*4}) : tensor<{R+4}xf32> -> tensor<2xf32>
    %activation_storage = check.generate.fill value(-77.0) : tensor<{A+4}xf32>
    %activation = check.tensor.view %activation_storage offset(8) : tensor<{A+4}xf32> -> tensor<{A}xf32>
    %activation_before = check.tensor.view %activation_storage offset(0) : tensor<{A+4}xf32> -> tensor<2xf32>
    %activation_after = check.tensor.view %activation_storage offset({(A+2)*4}) : tensor<{A+4}xf32> -> tensor<2xf32>
    %control = check.generate.fill value(0) : tensor<1048xi32>
    check.compare<@actual.{name},@reference.{name}>(%root,%input,%residual,%activation,%control) : (tensor<{BANK}xi8>,tensor<{R}xf32>,tensor<{R}xf32>,tensor<{A}xf32>,tensor<1048xi32>) -> () {{
      check.expect.close actual(%residual_storage) expected(%residual_storage) atol(0.0001) rtol(0.0001) nan(same) : tensor<{R+4}xf32>
      check.expect.close actual(%activation_storage) expected(%activation_storage) atol(0.000001) rtol(0.00001) nan(same) : tensor<{A+4}xf32>
      check.expect.bitwise actual(%input) expected(%input) : tensor<{R}xf32>
      check.expect.bitwise actual(%control) expected(%control) : tensor<1048xi32>
''')
    for field,typ in [('root_before','256xi8'),('root_after','256xi8'),('residual_before','2xf32'),('residual_after','2xf32'),('activation_before','2xf32'),('activation_after','2xf32')]:
        checks.append(f'      check.expect.bitwise actual(%{field}) expected(%{field}) : tensor<{typ}>\n')
    checks.append('    }\n  }\n  check.return\n}\n')
# Cross the old 32768-group ceiling and cover the full 69632-group capacity.
for rows in (257,512):
    name=f'ffn27_quantize_{rows}'
    groups=F//128
    packed=rows*groups*144
    count=rows*F
    h.emit(f'''func.def @test.init.{name}.body(%row0:index,%input:buffer) {{
  %row = index.assume %row0 [range(%row0,0,{rows-1})] : index
  %zero = index.constant 0 : index
  %one = index.constant 1 : index
  %width = index.constant {F} : index
  %rp = index.add %row,%one : index
  %ri = index.cast %rp : index to i32
  %rf = scalar.uitofp %ri : i32 to f32
  %u = scalar.constant 0.9921875 : f32
  %value = scalar.mulf %rf,%u : f32
  %origin = index.constant 0 : offset
  %view = buffer.view %input[%origin] : buffer -> view<{rows}x{F}xf32>
  scf.for %c = [%zero to %width step %one] {{
    view.store %value,%view[%row,%c] : f32,view<{rows}x{F}xf32>
  }}
  func.return
}}
kernel.def @test.init.{name}() {{
  %rows = index.constant {rows} : index
  %one = index.constant 1 : index
  kernel.launch.config workgroups(%rows,%one,%one) workgroup_size(%one,%one,%one) : index
}} launch(%input:buffer) {{
  %row = kernel.workgroup.id<x> : index
  func.call @test.init.{name}.body(%row,%input) : (index,buffer) -> ()
  kernel.return
}}
func.def @reference.{name}(%input:buffer,%packed:buffer) {{
  %zero = index.constant 0 : index
  %one = index.constant 1 : index
  %rows = index.constant {rows} : index
  %groups = index.constant {groups} : index
  %four = index.constant 4 : index
  %two = index.constant 2 : index
  %payload_begin = index.constant 16 : index
  %end = index.constant 144 : index
  %stride = index.constant 144 : offset
  %payload = scalar.constant 127 : i8
  %unit = scalar.constant 0.0078125 : f32
  %qsum = scalar.constant 4064.0 : f32
  scf.for %row = [%zero to %rows step %one] {{
    func.call @test.init.{name}.body(%row,%input) : (index,buffer) -> ()
    %rp = index.add %row,%one : index
    %ri = index.cast %rp : index to i32
    %rf = scalar.uitofp %ri : i32 to f32
    %d32 = scalar.mulf %rf,%unit : f32
    %s32 = scalar.mulf %d32,%qsum : f32
    %d = scalar.fptrunc %d32 : f32 to f16
    %sum = scalar.fptrunc %s32 : f32 to f16
    %first = index.mul %row,%groups : index
    scf.for %group = [%zero to %groups step %one] {{
      %number = index.add %first,%group : index
      %offset = index.scale %number,%stride : index,offset -> offset
      %header = buffer.view %packed[%offset] : buffer -> view<8xf16>
      %bytes = buffer.view %packed[%offset] : buffer -> view<144xi8>
      scf.for %b = [%zero to %four step %one] {{
        %di = index.mul %b,%two : index
        %si = index.add %di,%one : index
        view.store %d,%header[%di] : f16,view<8xf16>
        view.store %sum,%header[%si] : f16,view<8xf16>
      }}
      scf.for %b = [%payload_begin to %end step %one] {{
        view.store %payload,%bytes[%b] : i8,view<144xi8>
      }}
    }}
  }}
  func.return
}}
command.program.def public retain @actual.{name}() launch(%input:buffer,%packed:buffer) {{
  command.serial {{
    kernel.launch @test.init.{name}(%input) : (buffer)
    %rows = index.constant {rows} : index
    %width = index.constant {F} : index
    kernel.launch @ggml_quantize_q8_1_x4_f32[%rows,%width](%rows,%width,%input,%packed) : [index,index](index,index,buffer,buffer)
  }}
  command.return
}}
''')
    checks.append(f'''command.program.decl @actual.{name}() launch(%input:buffer,%packed:buffer)
func.decl @reference.{name}(%input:buffer,%packed:buffer)
check.scenario @{name} {{
  check.trial[1](%trial:index,%entropy:check.entropy) {{
    %input = check.generate.fill value(-7.0) : tensor<{count}xf32>
    %storage = check.generate.fill value(85) : tensor<{packed+128}xi8>
    %packed = check.tensor.view %storage offset(64) : tensor<{packed+128}xi8> -> tensor<{packed}xi8>
    %before = check.tensor.view %storage offset(0) : tensor<{packed+128}xi8> -> tensor<64xi8>
    %after = check.tensor.view %storage offset({packed+64}) : tensor<{packed+128}xi8> -> tensor<64xi8>
    check.compare<@actual.{name},@reference.{name}>(%input,%packed) : (tensor<{count}xf32>,tensor<{packed}xi8>) -> () {{
      check.expect.bitwise actual(%input) expected(%input) : tensor<{count}xf32>
      check.expect.bitwise actual(%storage) expected(%storage) : tensor<{packed+128}xi8>
      check.expect.bitwise actual(%before) expected(%before) : tensor<64xi8>
      check.expect.bitwise actual(%after) expected(%after) : tensor<64xi8>
    }}
  }}
  check.return
}}
''')
(ROOT/'ffn27_programs.loom').write_text(''.join(h.out))
(ROOT/'ffn27_checks.loom').write_text(''.join(checks))
