def anchors(rows, hidden, intermediate):
    # The actual path includes RMS normalization. Residual is constant per row,
    # gamma127/32, epsilon1e-6. First Q8 scale rounds to +/-1/32 in F16;
    # its127 codes recover exactly +/-127/32 for all selected residual rows.
    # This is independent of encoded weights and actual packed activation bytes.
    result = []
    for r in range(rows):
        initial = (-1 if r % 2 else 1) * (r + 1)
        normalized = h.f32(initial / math.sqrt(initial * initial + 1e-6) * (127 / 32))
        d0 = h.f16(h.f32(abs(normalized) / 127))
        assert d0 == 1 / 32
        x = (-127 if initial < 0 else 127) * d0
        values = []
        for c in range(4):
            gate = h.f32(x * (c + 1) * hidden / 4096)
            up = h.f32(x * (4 - c) * hidden / 8192)
            values.append(h.f32(h.f32(gate / (1 + math.exp(-gate))) * up))
        d = h.f32(max(map(abs, values)) / 127)
        inverse = h.f32(1 / d)
        codes = [round(h.f32(v * inverse)) for v in values]
        assert min(abs(abs(h.f32(v * inverse) - round(h.f32(v * inverse))) - .5) for v in values) > .01
        result.append([h.f32(initial + intermediate / 4 * sum(codes) * h.f16(d) * (c + 1) / 4096) for c in range(4)])
    return result

