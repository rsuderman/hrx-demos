"""Independent double-precision anchors for the fixed row-operation fixtures.

The pinned reference VM has no F64 transcendental lowering. Python's standard
math functions evaluate the mathematical RMS/GELU/rotation references offline;
the test still performs F64 weighting/basic arithmetic and F32 stage stores.
No GPU results or native approximate recipes participate in expected values.

check.generate.iota uses double(offset + ordinal * step), then casts to F32
(pinned value_materializer.c:1303). Owner views skip four F32 prefix elements.
"""

import argparse
import math
from pathlib import Path
import struct


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def iota(count, offset, step, skip=0):
    return [f32(offset + (skip + i) * step) for i in range(count)]


EPSILON = f32(1e-6)


def inverse_rms(values):
    return 1.0 / math.sqrt(math.fsum(v * v for v in values) / len(values) + EPSILON)


def weighted_rms(values, gamma):
    inverse = inverse_rms(values)
    return [f32(v * inverse * g) for v, g in zip(values, gamma)]


def emit_data():
    # Each bank has three row entries. Banks0/2 match four-element owner views.
    low1152 = iota(3 * 1152, -0.0002, 0.0000001, skip=4)
    low256 = iota(3 * 256, -0.0002, 0.0000001, skip=4)
    head = iota(256, -0.0002, 0.000001)
    update = iota(1152, -0.0002, 0.0000001)
    post_gamma = iota(1152, 1.5, 0.0001)
    residual = iota(1152, 0.5, 0.001)
    # Explicit F32 boundary after post RMS, then after residual addition.
    post = weighted_rms(update, post_gamma)
    summed = [f32(x + y) for x, y in zip(residual, post)]
    banks = [
        [inverse_rms(low1152[r * 1152 : (r + 1) * 1152]) for r in range(3)],
        [inverse_rms([0.0] * 1152)] * 3,
        [inverse_rms(low256[r * 256 : (r + 1) * 256]) for r in range(3)],
        [inverse_rms(head)] * 3,
        [inverse_rms(update)] * 3,
        [inverse_rms(summed)] * 3,
    ]
    # This case remains sensitive to the rejected downloaded1e-8 post epsilon.
    wrong = 1.0 / math.sqrt(math.fsum(v * v for v in update) / 1152 + f32(1e-8))
    assert abs(wrong / banks[4][0] - 1.0) > 1.0
    assert weighted_rms(update, post_gamma) != weighted_rms(
        update, [g + 1.0 for g in post_gamma]
    )

    gates = iota(3 * 6912, -20.0, 0.005, skip=4)
    gelu = [
        0.5
        * x
        * (1.0 + math.tanh(math.sqrt(2.0 / math.pi) * x * (1.0 + 0.044715 * x * x)))
        for x in gates
    ]
    assert min(gates) < -8 and max(gates) > 20 and 0.0 in gates
    cosines, sines = [], []
    # Same explicitly passed F32 log-step values; ideal F64 trigonometry.
    for base, size, position in [
        (10000, 256, 11),
        (1000000, 256, 513),
        (10000000, 64, 17),
    ]:
        log_step = f32(-2.0 * math.log(base) / size)
        for pair in range(size // 2):
            angle = float(position) * math.exp(pair * log_step)
            cosines.append(math.cos(angle))
            sines.append(math.sin(angle))

    arrays = {
        "oracle.rms.inverses": [v for bank in banks for v in bank],
        "oracle.geglu.values": gelu,
        "oracle.rotary.cosines": cosines,
        "oracle.rotary.sines": sines,
    }
    lines = [
        "// Copyright 2026 AMD ROCm Software",
        "// SPDX-License-Identifier: MIT",
        "// Generated by gemma3_reference.py; independent F64 mathematical anchors.",
    ]
    for name, values in arrays.items():
        data = struct.pack("<" + "d" * len(values), *values).hex()
        lines.append(f'global.rodata.def @{name} = bytes("{data}")')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).with_name("gemma3_reference_data.loom")
    window = Path(__file__).parents[2] / "attention/testing/gemma3_window_checks.loom"
    window_anchor = f"  %first_weight = scalar.constant {math.exp(0.0625)!r} : f64"
    assert window_anchor in window.read_text(), "window F64 exp anchor is stale"
    expected = emit_data()
    if args.check:
        assert path.read_text() == expected, "reference fixture is stale"
    else:
        path.write_text(expected)
    print(
        "Independent F64 anchors: 18 RMS inverses, 20736 GELU values, 288 rotary pairs"
    )


if __name__ == "__main__":
    main()
