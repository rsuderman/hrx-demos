import math
import struct
f32 = lambda x: struct.unpack('<f', struct.pack('<f', x))[0]
f16 = lambda x: struct.unpack('<e', struct.pack('<e', x))[0]
out = ['// Copyright 2026 AMD ROCm™ Software\n// SPDX-License-Identifier: MIT\n// Generated by fixtures.py; independently computed deterministic anchors.\n']

def emit(s): out.append(s)
def fp(x): return f'{float(x):.17g}' if float(x) != int(x) else f'{float(x):.1f}'
def kernel(name, groups, args, body):
    arguments=[part.strip().split(':')[0] for part in args.split(',')]
    semantic=body.replace('  %channel = kernel.workgroup.id<x> : index\n','')
    emit(f'func.def @{name}.body(%channel0: index, {args}) {{\n  %channel = index.assume %channel0 [range(%channel0, 0, {groups-1})] : index\n{semantic}\n  func.return\n}}\n')
    if name.startswith('test.expected.'):
        return
    emit(f'''kernel.def @{name}() {{
  %groups = index.constant {groups} : index
  %one = index.constant 1 : index
  kernel.launch.config workgroups(%groups, %one, %one) workgroup_size(%one, %one, %one) : index
}} launch({args}) {{
  %channel = kernel.workgroup.id<x> : index
  func.call @{name}.body(%channel, {', '.join(arguments)}) : (index, {', '.join('buffer' for _ in arguments)}) -> ()
  kernel.return
}}
''')

def reference(name, count, args, calls):
    emit(f'''func.def @reference.{name}({args}) {{
  %zero = index.constant 0 : index
  %one = index.constant 1 : index
  %end = index.constant {count} : index
  scf.for %channel = [%zero to %end step %one] {{
{calls}
  }}
  func.return
}}
''')

def input_body(rows, width, whole=False):
    # All transient rows are explicitly defined. No active-row guard is claimed.
    return f'''  %x = buffer.view %input[%origin] : buffer -> view<{rows}x{width}xf32>
  %r0 = index.constant 0 : index
  %rn = index.constant {rows} : index
  %cn = index.constant {width} : index
  %c32 = index.constant 32 : index
  %c8 = index.constant 8 : index
  %c4 = index.constant 4 : index
  %c2 = index.constant 2 : index
  %u = scalar.constant 0.9921875 : f32
  scf.if %is_zero {{
    scf.for %r = [%r0 to %rn step %one] {{
      %rp = index.add %r, %one : index
      scf.for %c = [%r0 to %cn step %one] {{
        %group = index.div %c, %c32 : index
        %g8 = index.rem %group, %c8 : index
        %gp = index.add %g8, %one : index
        %factor = index.mul %rp, {'%one' if whole else '%gp'} : index
        %fi = index.cast %factor : index to i32
        %ff = scalar.uitofp %fi : i32 to f32
        %v0 = scalar.mulf %ff, %u : f32
        %parity = index.rem {'%r, %c2' if whole else '%group, %c4'} : index
        %negative = index.cmp eq, %parity, {'%one' if whole else '%c2'} : index
        %nv = scalar.negf %v0 : f32
        %v = scf.select %negative, %nv, %v0 : f32
        view.store %v, %x[%r, %c] : f32, view<{rows}x{width}xf32>
      }}
    }}
  }}'''

# These deliberately different byte patterns test scale/min correction, Q5 high
# bits and Q6 signed per-16 scales. They are not random quantized weights.
def weight_body(tag, width, profile, buffer, label):
    block = {12:144,13:176,14:210}[tag]
    factor = '%inverse_channel' if profile == 'up' else '%channel_factor'
    divisor = {'proj':32,'gate':4096,'up':8192,'down':4096}[profile]
    code = 33 if profile == 'proj' else 17
    high = -86 if tag == 14 or profile == 'proj' else 0
    scale = -2 if tag == 14 and profile == 'proj' else 1
    if tag in (12,13):
        ranges = [(0,4,0), (4,8,1), (8,12,1 if profile=='proj' else 0),
                  (12,16,17 if profile=='proj' else 1)]
        ranges += [(16,144,code)] if tag==12 else [(16,48,high),(48,176,code)]
    else: ranges=[(0,128,code),(128,192,high),(192,208,scale),(208,210,0)]
    text=f'''  %b0_{label} = index.constant 0 : index
  %bn_{label} = index.constant {width//256} : index
  %stride_{label} = index.constant {block} : offset
  %row_bytes_{label} = index.constant {width//256*block} : offset
  %row_origin_{label} = index.scale %channel, %row_bytes_{label} : index, offset -> offset
  scf.for %b_{label} = [%b0_{label} to %bn_{label} step %one] {{
    %bo_{label} = index.scale %b_{label}, %stride_{label} : index, offset -> offset
    %o_{label} = index.add %row_origin_{label}, %bo_{label} : offset
    %bytes_{label} = buffer.view %{buffer}[%o_{label}] : buffer -> view<{block}xi8>
'''
    for n,(begin,end,value) in enumerate(ranges):
        text+=f'''    %lo_{label}{n} = index.constant {begin} : index
    %hi_{label}{n} = index.constant {end} : index
    %byte_{label}{n} = scalar.constant {value} : i8
    scf.for %i_{label}{n} = [%lo_{label}{n} to %hi_{label}{n} step %one] {{
      view.store %byte_{label}{n}, %bytes_{label}[%i_{label}{n}] : i8, view<{block}xi8>
    }}
'''
    text+=f'''    %divisor_{label} = scalar.constant {divisor}.0 : f32
    %cf_i_{label} = index.cast {factor} : index to i32
    %cf_f_{label} = scalar.uitofp %cf_i_{label} : i32 to f32
    %unit_d_{label} = scalar.divf %cf_f_{label}, %divisor_{label} : f32
'''
    if profile=='proj':
        text+=f'''    %bp_{label} = index.add %b_{label}, %one : index
    %bi_{label} = index.cast %bp_{label} : index to i32
    %bf_{label} = scalar.uitofp %bi_{label} : i32 to f32
    %d_f_{label} = scalar.mulf %unit_d_{label}, %bf_{label} : f32
'''
    else: text+=f'    %d_f_{label} = scalar.mulf %unit_d_{label}, %float_one : f32\n'
    text+=f'''    %d_{label} = scalar.fptrunc %d_f_{label} : f32 to f16
    %d_add_{label} = index.constant {208 if tag==14 else 0} : offset
    %d_o_{label} = index.add %o_{label}, %d_add_{label} : offset
    %d_view_{label} = buffer.view %{buffer}[%d_o_{label}] : buffer -> view<1xf16>
    view.store %d_{label}, %d_view_{label}[0] : f16, view<1xf16>
'''
    if tag !=14:
        text+=f'''    %min_add_{label} = index.constant 2 : offset
    %min_o_{label} = index.add %o_{label}, %min_add_{label} : offset
    %min_view_{label} = buffer.view %{buffer}[%min_o_{label}] : buffer -> view<1xf16>
    %min_f_{label} = scalar.constant {0.015625 if profile=='proj' else 0.0} : f32
    %min_{label} = scalar.fptrunc %min_f_{label} : f32 to f16
    view.store %min_{label}, %min_view_{label}[0] : f16, view<1xf16>
'''
    return text+'  }\n'

