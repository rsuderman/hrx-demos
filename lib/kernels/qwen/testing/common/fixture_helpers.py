def store_pattern(rows,width,buffer,values,label):
    # A bounded list of precomputed values, selected by row and channel mod4.
    text=f'''  %view_{label} = buffer.view %{buffer}[%origin] : buffer -> view<{rows}x{width}xf32>
'''
    for r in range(rows):
        v=values[r]
        for k in range(4): text+=f'  %v_{label}{r}_{k} = scalar.constant {fp(v[k])} : f32\n'
        text+=f'''  %m2_{label}{r} = index.constant 2 : index
  %m3_{label}{r} = index.constant 3 : index
  %p1_{label}{r} = index.cmp eq, %mod, %one : index
  %p2_{label}{r} = index.cmp eq, %mod, %m2_{label}{r} : index
  %p3_{label}{r} = index.cmp eq, %mod, %m3_{label}{r} : index
  %s1_{label}{r} = scf.select %p1_{label}{r}, %v_{label}{r}_1, %v_{label}{r}_0 : f32
  %s2_{label}{r} = scf.select %p2_{label}{r}, %v_{label}{r}_2, %s1_{label}{r} : f32
  %s3_{label}{r} = scf.select %p3_{label}{r}, %v_{label}{r}_3, %s2_{label}{r} : f32
'''
        if width==13:
            text+=f'  view.store %s3_{label}{r}, %view_{label}[{r}, %channel] : f32, view<{rows}x{width}xf32>\n'
        else:
            limit=f'%limit_{label}'
            if r==0:text+=f'  {limit} = index.constant {width} : index\n  %valid_{label} = index.cmp ult, %channel, {limit} : index\n'
            text+=f'  scf.if %valid_{label} {{\n    view.store %s3_{label}{r}, %view_{label}[{r}, %channel] : f32, view<{rows}x{width}xf32>\n  }}\n'
    return text

def ffn_anchors(rows, hidden, intermediate):
    """Closed-form logical FFN oracle, independent of encoded weight buffers."""
    initial = [[f32(-.25+r/16+k/64) for k in range(4)] for r in range(rows)]
    activation, result = [], []
    for r in range(rows):
        x = (-1 if r % 2 else 1) * (r+1) * 127/128
        h = []
        for k in range(4):
            g = f32(x * (k+1) * (hidden/4096))
            u = f32(x * (4-k) * (hidden/8192))
            h.append(f32(f32(g/(1+math.exp(-g))) * u))
        d = f32(max(map(abs,h))/127)
        inverse = f32(1/d)
        codes = [round(f32(v*inverse)) for v in h]
        assert min(abs(abs(f32(v*inverse)-round(f32(v*inverse)))-.5) for v in h) > .01
        activation.append(h)
        result.append([f32(initial[r][k] + (intermediate/4)*sum(codes)*f16(d)*(k+1)/4096) for k in range(4)])
    return initial, activation, result
