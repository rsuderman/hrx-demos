// Import supported C++ computation, then author its command using ordinary host
// C++. The importer does not author this command or introduce another dispatch.
#include <cstdio>
#include <memory>
#include <string_view>

#include "loomc/import/cxx.h"
#include "tools/loomify-gguf/authoring/command/command_program_builder.h"
#include "tools/loomify-gguf/authoring/computation/facade_headers.h"

namespace {
template <typename T, void (*Release)(T *)> struct Deleter {
  void operator()(T *value) const { Release(value); }
};
template <typename T, void (*Release)(T *)>
using Owner = std::unique_ptr<T, Deleter<T, Release>>;

bool Ok(loomc_status_t status) {
  bool ok = loomc_status_is_ok(status);
  if (!ok) {
    auto message = loomc_status_message(status);
    std::fprintf(stderr, "%.*s\n", static_cast<int>(message.size),
                 message.data);
  }
  loomc_status_free(status);
  return ok;
}

bool Succeeded(const loomc_result_t *result) {
  if (result && loomc_result_succeeded(result))
    return true;
  if (result) {
    for (size_t i = 0; i < loomc_result_diagnostic_count(result); ++i) {
      auto diagnostic = loomc_result_diagnostic_at(result, i);
      std::fprintf(stderr, "%.*s\n", static_cast<int>(diagnostic->message.size),
                   diagnostic->message.data);
    }
  }
  return false;
}

// Existing importer callback over pinned upstream headers. No filesystem
// include discovery or redefined facade types are needed for this bounded
// example.
loomc_status_t Header(void *, loomc_string_view_t path,
                      loomc_source_t **out_source) {
  *out_source = nullptr;
  std::string_view name(path.data, path.size);
  constexpr std::string_view prefix = "/loomify/include/loomcxx/";
  if (name.substr(0, prefix.size()) != prefix)
    return loomc_ok_status();
  name.remove_prefix(prefix.size());
  const auto *headers = facade_headers_create();
  for (size_t i = 0; i < facade_headers_size(); ++i) {
    if (name != headers[i].name)
      continue;
    loomc_source_options_t options = {};
    options.identifier = path;
    options.contents = loomc_make_byte_span(headers[i].data, headers[i].size);
    options.storage = LOOMC_SOURCE_STORAGE_COPY;
    return loomc_source_create(&options, loomc_allocator_system(), out_source);
  }
  return loomc_ok_status();
}

loomc_status_t LogicalPath(void *, loomc_string_view_t path,
                           loomc_string_view_t *out_identifier) {
  constexpr std::string_view prefix = "/loomify/include/";
  const std::string_view name(path.data, path.size);
  *out_identifier = path;
  if (name.substr(0, prefix.size()) == prefix) {
    out_identifier->data += prefix.size();
    out_identifier->size -= prefix.size();
  }
  return loomc_ok_status();
}
} // namespace

int main(int argc, char **argv) {
  if (argc != 3) {
    std::fprintf(stderr, "usage: emit_example COMPUTATION.cc OUTPUT.loombc\n");
    return 1;
  }
  loomc_context_t *context = nullptr;
  if (!Ok(loomc_context_create(nullptr, loomc_allocator_system(), &context)))
    return 1;
  Owner<loomc_context_t, loomc_context_release> context_owner(context);
  loomc_workspace_t *workspace = nullptr;
  if (!Ok(loomc_workspace_create(nullptr, loomc_allocator_system(),
                                 &workspace)))
    return 1;
  Owner<loomc_workspace_t, loomc_workspace_release> workspace_owner(workspace);
  loomc_source_t *source = nullptr;
  // Use a logical identity in the imported module rather than retaining a
  // machine-specific build/sandbox path in the generated bytecode.
  loomc_source_load_options_t source_options = {};
  source_options.identifier = loomc_make_cstring_view("affine.cc");
  if (!Ok(loomc_source_create_from_path(loomc_make_cstring_view(argv[1]),
                                        &source_options,
                                        loomc_allocator_system(), &source)))
    return 1;
  Owner<loomc_source_t, loomc_source_release> source_owner(source);
  loomc_cxx_import_options_t import_options = {};
  const auto include_path = loomc_make_cstring_view("/loomify/include");
  import_options.flags = LOOMC_CXX_IMPORT_FLAG_NO_BUILTIN_INCLUDES;
  import_options.source_provider.fn = Header;
  import_options.source_path_mapper.fn = LogicalPath;
  import_options.system_include_paths = &include_path;
  import_options.system_include_path_count = 1;
  const auto root = loomc_make_cstring_view("authored_affine");
  import_options.roots = &root;
  import_options.root_count = 1;
  loomc_module_t *imported = nullptr;
  loomc_result_t *result = nullptr;
  if (!Ok(loomc_module_import_cxx(context, workspace, source, &import_options,
                                  loomc_allocator_system(), &imported,
                                  &result)))
    return 1;
  Owner<loomc_module_t, loomc_module_release> imported_owner(imported);
  Owner<loomc_result_t, loomc_result_release> import_result(result);
  if (!Succeeded(result))
    return 1;
  // Imported definitions own their computation; frontend source may be
  // released.
  source_owner.reset();

  using namespace hrx::loomify_gguf;
  std::unique_ptr<ModuleBuilder> module;
  if (!Ok(ModuleBuilder::Create(context, workspace, imported, &module)))
    return 1;
  imported_owner.reset();
  KernelRef affine;
  if (!Ok(module->Kernel("authored.affine", &affine)))
    return 1;
  std::unique_ptr<CommandProgramBuilder> program;
  if (!Ok(module->DefineProgram("example.authored_affine", {}, 2, &program)))
    return 1;
  if (!Ok(program->Invoke(affine, {},
                          {program->Binding(0), program->Binding(1)})) ||
      !Ok(program->Finish()))
    return 1;
  loomc_module_t *complete = nullptr;
  result = nullptr;
  if (!Ok(module->LinkAndVerify({program->Ref()}, &complete, &result)))
    return 1;
  Owner<loomc_module_t, loomc_module_release> complete_owner(complete);
  Owner<loomc_result_t, loomc_result_release> link_result(result);
  if (!Succeeded(result))
    return 1;
  loomc_module_serialize_options_t options = {};
  options.format = LOOMC_SOURCE_FORMAT_BYTECODE;
  return Ok(loomc_module_serialize_to_path(complete, &options,
                                           loomc_make_cstring_view(argv[2]),
                                           loomc_allocator_system()))
             ? 0
             : 1;
}
